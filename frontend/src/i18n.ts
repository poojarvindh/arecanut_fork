/**
 * Translate an English UI string. Anything not in KN_TEXT falls back to the
 * English text it was given, so a missing entry degrades to English rather
 * than rendering blank.
 */
export function t(text: string | undefined | null, lang: Lang): string {
  if (!text) return "";
  if (lang !== "kn") return text;
  return KN_TEXT[text] ?? text;
}
